function backup(name, data) {
    fs.mkdirSync(BACKUP_DIR, { recursive: true });
    const file = path.join(BACKUP_DIR, `${name}-${Date.now()}.json`);
    fs.writeFileSync(file, JSON.stringify(data, null, 2));
    console.log(`  สำรอง → ${path.relative(process.cwd(), file)}`);
}

async function load(courseId, lessonId) {
    const ref = db.collection('courses').doc(courseId).collection('lessons').doc(lessonId);
    const snap = await ref.get();
    if (!snap.exists) throw new Error(`ไม่พบบทเรียน ${courseId}/${lessonId}`);
    const data = snap.data();
    const questions = JSON.parse(data.content);
    if (!Array.isArray(questions)) throw new Error('content ไม่ใช่อาร์เรย์ข้อสอบ');
    return { ref, data, questions };
}

/** ตั้งคำตอบใหม่โดยไม่สนว่าชุดนั้นเก็บเป็น answerIndex หรือ correctIndex */
function setAnswer(q, idx) {
    if ('answerIndex' in q) q.answerIndex = idx;
    if ('correctIndex' in q) q.correctIndex = idx;
    if (!('answerIndex' in q) && !('correctIndex' in q)) q.correctIndex = idx;
}
const getAnswer = (q) => q.answerIndex ?? q.correctIndex ?? q.correctAnswer;

