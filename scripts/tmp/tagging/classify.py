"""จัดระดับความยาก + ทักษะ จากตัวโจทย์และเฉลย

ระดับ: ให้คะแนนความซับซ้อนแล้ว "จัดอันดับภายในชุดเดียวกัน" แล้วตัดที่ 25/40/25/10
       (เทียบกันเองในบทเดียวกัน แม่นกว่าตัดสินแบบข้ามชั้นข้ามบท)
ทักษะ: ดูรูปแบบภาษา — สัญลักษณ์ล้วน=คิดเลข · ถามนิยาม/ข้อใดถูก=เข้าใจ · มีบริบทเรื่องราว=แปลโจทย์
"""
import re

TH = re.compile(r'[฀-๿]')
# คำที่บอกว่าเป็นโจทย์เชิงสถานการณ์
CTX = ['ร้าน','แม่ค้า','พ่อค้า','นักเรียน','ครู','โรงเรียน','บาท','กิโลกรัม','เมตร','ชั่วโมง',
       'นาที','วัน','เดือน','ปี','คน','ซื้อ','ขาย','เดินทาง','รถ','สวน','ไร่','ห้อง','กล่อง',
       'ถุง','เงิน','ราคา','อายุ','น้ำหนัก','ความยาว','พื้นที่','ปริมาตร','ระยะทาง','ความเร็ว']
# คำที่บอกว่าถามความเข้าใจ/นิยาม
CONCEPT = ['ข้อใดถูกต้อง','ข้อใดไม่ถูกต้อง','ข้อใดกล่าว','ข้อใดเป็นจริง','ข้อใดเป็นเท็จ',
           'เป็นจำนวนชนิดใด','ข้อใดต่อไปนี้','นิยาม','สมบัติใด','ข้อความใด','เพราะเหตุใด',
           'ข้อใดคือ','ข้อใดสอดคล้อง','ข้อใดเรียง','ข้อใดมีความหมาย','จงพิจารณา']


def skill(q, expl=''):
    s = str(q)
    th = len(TH.findall(s))
    if any(k in s for k in CONCEPT):
        return 'เข้าใจ'
    ctx = sum(1 for k in CTX if k in s)
    # โจทย์สถานการณ์: ไทยเยอะ + มีคำบริบท
    if th >= 70 and ctx >= 2:
        return 'แปลโจทย์'
    if th >= 110 and ctx >= 1:
        return 'แปลโจทย์'
    # สัญลักษณ์เยอะ ไทยน้อย = คิดเลขล้วน
    if th < 60 or s.count('$') >= 2:
        return 'คิดเลข'
    return 'เข้าใจ' if ctx == 0 else 'คิดเลข'


def score(q, expl):
    """คะแนนความซับซ้อน — ใช้จัดอันดับภายในชุด ไม่ใช่ค่าสัมบูรณ์"""
    s, e = str(q), str(expl)
    steps = e.count('$$') // 2                    # จำนวนขั้นสมการในเฉลย
    return (len(s) * 0.9
            + steps * 26
            + len(e) * 0.09
            + len(TH.findall(s)) * 0.35
            + s.count('$') * 3
            + 30 * len(re.findall(r'ถ้า|แล้ว|เมื่อ|จากนั้น|ต่อมา|หลังจาก', s)))


CUT = [('ง่าย', .25), ('กลาง', .40), ('ยาก', .25), ('ยากมาก', .10)]


def rank_levels(items):
    """items = [(key, score)] → dict key -> ระดับ  โดยตัดตามสัดส่วนมาตรฐาน"""
    order = sorted(items, key=lambda t: t[1])
    n = len(order)
    out, i = {}, 0
    for k, (lab, frac) in enumerate(CUT):
        take = n - i if k == len(CUT) - 1 else round(n * frac)
        for key, _ in order[i:i + take]:
            out[key] = lab
        i += take
    return out
