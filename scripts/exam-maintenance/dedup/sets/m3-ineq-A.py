def sol(rel):
    """แก้อสมการสดด้วย SymPy คืนเป็นเซตคำตอบ (เทียบเซตกันตรงๆ ไม่ติดรูปแบบการเขียน)"""
    return sp.solve_univariate_inequality(rel, x, relational=False)


def same(rel, expected):
    """จริงเมื่อเซตคำตอบของ rel ตรงกับเซตคำตอบของอสมการที่คาดไว้"""
    return sol(rel) == expected.as_set()


