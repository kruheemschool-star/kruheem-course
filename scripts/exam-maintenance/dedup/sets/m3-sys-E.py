def nsol(e1, e2):
    """0 = ไม่มีคำตอบ · 1 = คำตอบเดียว · 2 = มากมายไม่จำกัด"""
    r = sp.linsolve([e1.lhs - e1.rhs, e2.lhs - e2.rhs], (X, Y))
    if r == sp.EmptySet:
        return 0
    return 2 if list(r)[0].free_symbols else 1


