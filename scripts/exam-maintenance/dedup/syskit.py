import sympy as sp

X, Y = sp.symbols('x y', real=True)
CH, ST, GR = 'ระบบสมการเชิงเส้นสองตัวแปร', 'จำนวนและพีชคณิต', 'ม.3'

# หัวข้อย่อยของบล็อกที่เขียนใหม่ (ของเดิมเป็นโจทย์ปัญหาล้วน ไม่มีพีชคณิตบริสุทธิ์เลย)
MEAN = 'ความหมายและการตรวจคำตอบของระบบสมการ'
SUBS = 'การแก้ระบบสมการด้วยวิธีแทนค่า'
ELIM = 'การแก้ระบบสมการด้วยวิธีกำจัดตัวแปร'
FRAC = 'ระบบสมการที่มีเศษส่วนและทศนิยม'
NSOL = 'จำนวนคำตอบของระบบสมการ'
GRAPH = 'กราฟของระบบสมการและจุดตัด'
COEF = 'การหาค่าคงตัวจากเงื่อนไขคำตอบ'
REARR = 'ระบบสมการที่ต้องจัดรูปก่อนแก้'


def T(sub, skill, lv):
    return [CH, sub, ST, GR, skill, lv]


def S(e1, e2):
    """แก้ระบบสดด้วย SymPy คืน (x, y) — ยืนยันว่ามีคำตอบเดียวจริง"""
    r = sp.solve([sp.Eq(e1.lhs - e1.rhs, 0), sp.Eq(e2.lhs - e2.rhs, 0)], [X, Y], dict=True)
    assert len(r) == 1, ('ไม่ได้คำตอบเดียว', r)
    return sp.nsimplify(r[0][X]), sp.nsimplify(r[0][Y])


def N(v):
    """คืนสตริงตัวเลขแบบที่ใช้เป็นตัวเลือก"""
    v = sp.nsimplify(v)
    assert v == sp.Integer(v), ('ไม่ใช่จำนวนเต็ม', v)
    return str(int(v))


def P(a, b):
    """คู่อันดับในรูป LaTeX"""
    return r'$(%s, %s)$' % (N(a), N(b))


def holds(eq, xv, yv):
    """จริงเมื่อคู่อันดับ (xv, yv) สอดคล้องกับสมการ"""
    return sp.simplify((eq.lhs - eq.rhs).subs({X: xv, Y: yv})) == 0
